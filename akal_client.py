"""AkAl Client Wrapper

Provides a simple helper to call the Akal model endpoint using the same request format as OpenAI-style chat completions.

The function reads configuration from `config.py` (environment variables `AKAL_API_URL` and `AKAL_API_KEY`).
"""
import httpx
from config import settings
import logging

logger = logging.getLogger("hermes.akl_client")

def call_akal(system_instruction: str, user_prompt: str) -> str:
    """Send a chat request to the Akal API and return the model's reply.

    Args:
        system_instruction: System‑level prompt defining assistant behavior.
        user_prompt: The user's actual query.

    Returns:
        The content string generated by the model.
    """
    url = settings.AKAL_API_URL
    headers = {
        "Authorization": f"Bearer {settings.AKAL_API_KEY}",
        "Content-Type": "application/json",
    }
    payload = {
        "model": settings.GEMINI_MODEL,  # reuse the model name configured for other providers
        "messages": [
            {"role": "system", "content": system_instruction},
            {"role": "user", "content": user_prompt},
        ],
    }
    try:
        with httpx.Client(timeout=15.0) as client:
            resp = client.post(url, json=payload, headers=headers)
            resp.raise_for_status()
            data = resp.json()
            # Assume OpenAI‑compatible response format
            return data["choices"][0]["message"]["content"]
    except Exception as e:
        logger.error(f"Akal request failed: {e}")
        return ""
